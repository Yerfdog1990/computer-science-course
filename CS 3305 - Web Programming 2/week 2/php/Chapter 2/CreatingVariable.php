<?php

# Create and initialise the variable
$body_temp = 98.6 ;

# Display the variable value alone
echo $body_temp ;

# Display the variable inside a mixed string (double quotes)
echo "<p>Body temperature is $body_temp degrees Fahrenheit " ;

# Reassign a new value to the variable
$body_temp = 37.0 ;

# Display the new value in another mixed string
echo "( $body_temp degrees Celsius )</p>" ;

$num1 = 10 ;
$num2 = 20 ;
$sum = $num1 + $num2 ;

echo "<p>$num1 + $num2 = $sum <p/>";


